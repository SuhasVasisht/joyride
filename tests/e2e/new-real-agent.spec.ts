import fs from "node:fs";
import path from "node:path";
import { test, expect } from "@playwright/test";
import { call, PORT, waitUntil } from "./map-seed";
import { shot } from "./shot";
import { panTo } from "./chart-pan";
import { liveStdout } from "../fixtures/quota";
import type { NewReceipt } from "../../src/shared/freeform";

test("real Haiku discovers an artifact and records its link on the canvas with Undo", async ({ page }) => {
  test.skip(process.env.E2E_NEW_REAL_JOB !== "1", "Run scripts/lab-new-freeform.sh with the guarded named lab.");
  test.setTimeout(240000);
  const env = { ...JSON.parse(fs.readFileSync(`/tmp/joyride-e2e-${PORT}/env.json`, "utf8")), FM_HOME: process.env.E2E_LAB_FM_HOME!, JOYRIDE_HERDR_SOCKET: process.env.E2E_LAB_HERDR_SOCKET!, JOYRIDE_CLAUDE_DIR: process.env.E2E_LAB_CLAUDE_DIR! };
  expect(env.FM_HOME).not.toBe(path.resolve(".joyride/firstmate"));
  expect(env.JOYRIDE_HERDR_SOCKET).toContain(`/sessions/${process.env.E2E_NEW_LAB_SESSION}/`);
  expect(fs.existsSync(path.join(env.FM_HOME, ".fm-lab-home"))).toBe(true);
  await call("POST", "/api/usage/test-fake", { result: { kind: "ok", stdout: liveStdout(Date.now()) } });
  const idea = "new-real-agent";
  expect((await call("POST", "/api/missions", { id: idea, title: "New real-agent proof", goal: "Link a found artifact through New.", repos: [process.env.E2E_NEW_LAB_PROJECT], sessions: [] })).status).toBe(201);
  expect((await call("PUT", "/api/system/config", { workers: { permission_mode: "auto" } })).status).toBe(200);
  const artifact = await call("POST", "/api/artifacts", { title: "Heliotrope export analysis", url: "https://example.com/heliotrope-export", summary: "A sandbox artifact for real-agent lookup.", mission: idea });
  expect(artifact.status).toBe(201);
  await page.goto(`/#/compose?idea=${idea}`);
  const box = page.locator('[data-rail="new"]');
  await expect(box.getByRole("textbox", { name: "New", exact: true })).toBeFocused();
  await box.getByRole("textbox", { name: "New", exact: true }).fill("Find the artifact titled Heliotrope export analysis and link it here. Use its artifact: reference, not an external search. Do the job and finish your callback.");
  const response = page.waitForResponse((r) => r.url().endsWith("/api/new") && r.request().method() === "POST");
  await box.getByRole("textbox", { name: "New", exact: true }).press("Enter");
  const receipt: NewReceipt = await (await response).json();
  expect(receipt, receipt.message).toMatchObject({ route: "agent", state: "running" });
  expect(receipt.worker).toBeTruthy(); expect(receipt.session).toMatch(/^claude:/);
  await expect(box.locator("[data-new-result]")).toBeVisible();
  await page.waitForTimeout(850);
  await expect(box.locator("[data-new-result]")).toHaveCSS("opacity", "1");
  await shot(page, "new-freeform", "real-agent-start");
  const done = await waitUntil(async () => {
    const r = (await call<NewReceipt>("GET", `/api/new/${receipt.id}`)).body;
    if (r.state === "failed") throw new Error(r.message);
    return r.state === "done" ? r : false;
  }, 180000);
  if (!done) throw new Error("The agent did not complete.");
  expect(done.undo).toBe(true);
  const restingWorker = await waitUntil(async () => {
    const w = (await call<{ status: string }>("GET", `/api/workers/${encodeURIComponent(receipt.worker!)}`)).body;
    return ["idle", "done", "exited"].includes(w.status) ? w : false;
  }, 30000);
  expect(restingWorker, "The agent must finish its turn before the completed canvas capture.").toBeTruthy();
  const notes = (await call<{ id: string; bullets: string[]; scope: string }[]>("GET", `/api/notes?mission=${idea}`)).body;
  const linked = notes.find((n) => n.bullets.some((b) => b.includes(`artifact:${artifact.body.id}`)));
  expect(linked).toBeTruthy(); expect(linked!.scope).toBe(`mission:${idea}`);
  expect((await call("GET", `/api/notes/${linked!.id}`)).body.provenance.type).toBe("agent");
  await expect(box.locator('[data-new-result]')).toHaveAttribute("data-state", "done");
  await box.getByRole("button", { name: "Show on map" }).click();
  await expect(page.locator(`[data-board-item="${linked!.id}"]`).first()).toBeVisible();
  await page.waitForTimeout(850);
  await panTo(page.locator(`[data-board-item="${linked!.id}"]`).first());
  await expect(page.locator(".note-card").filter({ hasText: "Open the agent from the New receipt." }).first()).not.toContainText("[Open agent]");
  await page.getByRole("button", { name: "Fit", exact: true }).click();
  await expect(page.getByTestId("firstmate-node")).toBeInViewport({ ratio: .999 });
  await expect(page.locator(`[data-board-item="${linked!.id}"]`).first()).toBeInViewport({ ratio: .999 });
  await shot(page, "new-freeform", "real-agent-result");
  await page.getByRole("radio", { name: "Mid", exact: true }).click();
  await panTo(page.locator(`[data-board-item="${linked!.id}"]`).first());
  await page.locator(`[data-board-item="${linked!.id}"]`).first().screenshot({ path: "docs/checkpoints/new-freeform/real-agent-card.png" });
  await box.locator('[data-new-result][data-state="done"]').screenshot({ path: "docs/checkpoints/new-freeform/real-agent-receipt.png" });
  // Save provenance without credentials: the actual assistant model and the recorded owner result.
  const transcriptFiles = fs.readdirSync(env.JOYRIDE_CLAUDE_DIR + "/projects", { recursive: true }).filter((f) => typeof f === "string" && f.endsWith(`${receipt.session!.slice(7)}.jsonl`));
  expect(transcriptFiles.length).toBeGreaterThan(0);
  const transcript = fs.readFileSync(path.join(env.JOYRIDE_CLAUDE_DIR, "projects", String(transcriptFiles[0])), "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l));
  const models = [...new Set(transcript.map((l) => l.message?.model).filter((m) => m && m !== "<synthetic>"))];
  expect(models.some((m) => /haiku/i.test(m))).toBe(true);
  fs.writeFileSync("docs/reports/new-freeform-real-agent.json", JSON.stringify({ at: new Date().toISOString(), fake: false, models, session: receipt.session, worker: receipt.worker, labSession: process.env.E2E_NEW_LAB_SESSION, receipt: done, linked, screenshots: ["real-agent-start.png", "real-agent-result.png", "real-agent-card.png", "real-agent-receipt.png"] }, null, 2) + "\n");
  await box.getByRole("button", { name: "Undo", exact: true }).click();
  await expect(box.locator('[data-new-result]')).toHaveAttribute("data-state", "undone");
  expect((await call<{ id: string }[]>("GET", `/api/notes?mission=${idea}`)).body.some((n) => n.id === linked!.id)).toBe(false);
});
