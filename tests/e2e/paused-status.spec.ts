import fs from "node:fs";
import path from "node:path";
import { test, expect } from "@playwright/test";
import { buildFirstmateHome, FIXTURE_TASKS as T } from "./crew-fixture";
import { call, PORT, herdr, waitUntil } from "./map-seed";
import { shot } from "./shot";

test("self-wait stays active on the task card and Firstmate hub", async ({ page }) => {
  const env = JSON.parse(fs.readFileSync(`/tmp/joyride-e2e-${PORT}/env.json`, "utf8"));
  const home = path.join(env.JOYRIDE_RUNTIME, "firstmate");
  expect(home.startsWith(`/tmp/joyride-e2e-${PORT}/`)).toBe(true);
  const mission = "paused-checks";
  await call("POST", "/api/missions", { id: mission, title: "Check the export", goal: "Verify the export" });
  buildFirstmateHome(home, mission);
  fs.writeFileSync(path.join(home, "state", `${T.ship}.status`), `paused [at=${Math.floor(Date.now() / 1000)}]: e2e checks running; resumes when they exit\n`);
  await herdr("fake.add_pane", { cwd: "/tmp/joyride-fixture-firstmate", agent: "claude", agent_status: "working", name: "firstmate", title: "firstmate", label: "firstmate" });
  await waitUntil(async () => (await call("GET", `/api/firstmate/tasks/${T.ship}`)).body?.status === "paused");
  await page.setViewportSize({ width: 1600, height: 1600 });
  await page.goto("/#/");
  const node = page.getByTestId("firstmate-node");
  await expect(node).toHaveAttribute("data-firstmate", "running");
  const idea = page.locator(`.mission-node[data-mission="${mission}"]`);
  await expect(idea).toBeVisible();
  await idea.locator(".mn-title").focus();
  await page.getByRole("radio", { name: "Near", exact: true }).click();
  await expect(page.locator(".map-viewport")).toHaveAttribute("data-zoom", "near");
  await idea.locator(".mn-title").focus();
  const card = idea.locator(`.task-card[data-task="${T.ship}"]`);
  await expect(card).toHaveClass(/tone-working/);
  await expect(card.locator(".tc-status")).toHaveText("Moving");
  await expect(card.locator(".tc-status")).toHaveAttribute("title", "e2e checks running; resumes when they exit");
  await expect(card.locator(".tc-now")).toContainText("e2e checks running; resumes when they exit");
  await expect(card.locator(".tc-status")).not.toContainText("Paused");
  await shot(page, "CP3b", "paused-worker-active-card");
  await node.locator(".fm-title").focus();
  await expect(node.locator('[data-fm="ticker"]')).toContainText("Waiting on its own run", { timeout: 20000 });
  await expect(node.locator('[data-fm="ticker"]')).toContainText("e2e checks running; resumes when they exit");
  await shot(page, "CP3b", "paused-worker-active-hub");
  await page.goto(`/#/task/${T.ship}`);
  const sheet = page.getByRole("dialog");
  await expect(sheet.locator(".chip.working").filter({ hasText: "Waiting on its own run" })).toBeVisible();
});
